"""
🔗 مشاركة البيانات وتراكمها عبر الشنطة (self) - Sharing Data Between Methods

تطبيق توضيحي يشرح:
1. كيف الشنطة (self) بتحفظ البيانات من دالة وتخلي دالة ثانية تقدر تقرأها وتتذكرها!
2. كيف القائمة بتتراكم وبيكبر حجمها خطوة بخطوة جوة الـ Loop.
"""


class DataSharingDemo:

    def __init__(self):
        self.grades = []  # 1. عملنا شنطة فاضية للدرجات
        self.b = []  # عملنا شنطة فاضية للأرقام b

    # --- الفكرة الأولى: مشاركة البيانات بين الدوال ---
    def K(self):
        d = 85
        self.grades.append(d)  # ختينا 85 في الشنطة
        self.grades.append(90)  # ضفنا درجات إضافية للنية
        self.grades.append(78)

    def احسب_المتوسط(self):
        print("--- 1️⃣ تجربة مشاركة البيانات بين الدوال ---")
        print("محتوى الشنطة:", self.grades)  # [85, 90, 78] ← لسه متذكراهم!
        if len(self.grades) > 0:
            print("المتوسط الحسابي:", sum(self.grades) / len(self.grades))

    # --- الفكرة الثانية: متابعة تراكم البيانات جوة الشنطة ---
    def S(self):
        print("\n--- 2️⃣ تجربة تراكم الأرقام جوة الشنطة خطوة بخطوة ---")
        a = 1
        while a <= 10:
            print("الرقم الحالي:", a)
            self.b.append(a)  # كل مرة نخت الرقم في الشنطة
            print("الشنطة فيها شنو حالياً:", self.b)  # ونشوف الشنطة فيها شنو
            a += 1


# --- تشغيل وتجربة الكود ---
demo = DataSharingDemo()

# تجربة الفكرة الأولى
demo.K()
demo.احسب_المتوسط()

# تجربة الفكرة الثانية
demo.S()
