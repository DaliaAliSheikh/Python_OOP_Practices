"""
⚙️ الفرق بين دالة البناء والدوال العادية - Constructor vs Methods

برنامج يوضح مفهوم الـ __init__ وكيف تعمل تلقائياً عند إنشاء الكائن (Object)،
مقارنة بالدوال العادية (Methods) التي تتطلب استدعاءً صريحاً.
"""


class Player:
    def __init__(self, name):
        self.name = name
        # هذه الجملة ستطبع تلقائياً عند إنشاء الكائن
        print("تم إنشاء اللاعب:", self.name, "بنجاح! 🎮")

    def play(self):
        # هذه الدالة لن تعمل إلا بعد استدعائها
        print("اللاعب", self.name, "يلعب الآن... ⚽")


# 1. بمجرد السطر ده، حتشتغل الـ __init__ براها
player1 = Player("Ali")

# 2. الدالة دي حتشتغل لأننا استدعيناها بنفسنا
player1.play()
