"""
💡 الفرق بين __init__ والدوال العادية - __init__ vs Methods

تطبيق توضيحي يشرح مفاهيم الـ OOP:
- __init__: التجهيز والتهيئة تلقائياً فور إنشاء الكائن.
- الدوال العادية: استدعاؤها يدوي في أي وقت وبأي عدد من المرات.
- الاستمرارية: الشنطة (القائمة) بتظل محتفظة ببياناتها بين كل استدعاء والتاني.
"""


class GradeSystem:

    def __init__(self):  # 1. التجهيز - بيشتغل براهو أول ما ننشئ الكائن
        self.grades = []  # جهزنا الشنطة فاضية
        print("⚙️ [__init__] اشتغلت براهها وتجهزت الشنطة فاضية!")

    def K(self):  # 2. العملية - بناديها بنفسنا وقت ما نحب
        print("\n--- 📝 ننادي دالة التسجيل K() ---")
        grade = int(input("أدخل درجة لتسجيلها: "))
        self.grades.append(grade)
        print("محتوى الشنطة حالياً:", self.grades)


# --- تجربة التشغيل والتطبيق ---

# 1. إنشاء الكائن (الدالة __init__ بتشتغل براهنا هنا تلقائياً)
w = GradeSystem()  # ← __init__ اشتغل براهو هنا

# 2. ننادي الدالة المرة الأولى
w.K()  # ← انا ناديت K هنا

# 3. ننادي نفس الدالة المرة الثانية
w.K()  # ← ممكن اناديها تاني عادي والبيانات السابقة حتفضل محفوظة!
